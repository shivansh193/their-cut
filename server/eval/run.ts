// Accuracy eval over every fixture. Run: npm run eval        (re-analyses with Gemini, caches results)
//                                      npm run eval -- --cached (scores the cached analysis.json only)
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { analysePresence, type PresenceResult } from "../analysis/presence.js";
import { iou, lineLevel, precisionRecall } from "./metrics.js";

const ROOT = resolve(import.meta.dirname, "..", "..");
const FX = join(ROOT, "fixtures", "videos");
const cachedOnly = process.argv.includes("--cached");
const only = process.argv.find((a) => a.startsWith("--only="))?.split("=")[1];
const spec = JSON.parse(readFileSync(join(FX, "spec.json"), "utf8"));
const tags = spec.children.map((c: any) => ({
  id: c.id,
  name: c.name,
  description: c.description,
  images: [readFileSync(join(FX, "references", `${c.id}.jpg`))],
}));

const rows: any[] = [];
const narrAll = { tp: 0, fp: 0, fn: 0 };
for (const id of readdirSync(FX).filter((d) => existsSync(join(FX, d, "truth.json")))) {
  if (only && id !== only) continue;
  const truth = JSON.parse(readFileSync(join(FX, id, "truth.json"), "utf8"));
  const cache = join(FX, id, "analysis.json");
  let res: PresenceResult;
  if (cachedOnly || (existsSync(cache) && process.argv.includes("--reuse"))) {
    if (!existsSync(cache)) { console.log(`skip ${id}: no cache`); continue; }
    res = JSON.parse(readFileSync(cache, "utf8"));
  } else {
    console.log(`analysing ${id} (${truth.durationSec}s)…`);
    res = await analysePresence({ video: readFileSync(join(FX, id, "video.mp4")), durationSec: truth.durationSec, children: tags });
    writeFileSync(cache, JSON.stringify(res, null, 2));
    console.log(`  done in visual ${res.ms.visual}ms / narration ${res.ms.narration}ms`);
  }
  for (const c of res.children) {
    const t = truth.children[c.childId];
    const vKeep = c.visual.filter((i) => i.confidence >= 0.5);
    rows.push({
      video: id,
      child: c.childId,
      truthPct: t.presencePct,
      predPct: +c.presencePct.toFixed(2),
      errPts: +(c.presencePct - t.presencePct).toFixed(2),
      iouPresence: +iou(c.presence, t.presence).toFixed(3),
      iouVisual: +iou(vKeep, t.visual).toFixed(3),
      narrTime: precisionRecall(c.narration.filter((i) => i.confidence >= 0.5), t.narration),
    });
  }
  const ll = lineLevel(
    res.transcript.map((l) => ({ start: l.start, end: l.end, subjects: l.subjects.filter((s) => s.confidence >= 0.5).map((s) => s.childId) })),
    truth.narration,
  );
  narrAll.tp += ll.tp; narrAll.fp += ll.fp; narrAll.fn += ll.fn;
}

const mae = rows.reduce((s, r) => s + Math.abs(r.errPts), 0) / rows.length;
const meanIou = rows.reduce((s, r) => s + r.iouPresence, 0) / rows.length;
const meanIouV = rows.reduce((s, r) => s + r.iouVisual, 0) / rows.length;
const np = narrAll.tp / Math.max(1, narrAll.tp + narrAll.fp), nr = narrAll.tp / Math.max(1, narrAll.tp + narrAll.fn);

console.table(rows.map((r) => ({ video: r.video, child: r.child, truth: r.truthPct, pred: r.predPct, err: r.errPts, IoU: r.iouPresence, IoU_visual: r.iouVisual })));
console.log(`\nPresence error (mean abs): ${mae.toFixed(2)} pts | mean IoU ${meanIou.toFixed(3)} (visual only ${meanIouV.toFixed(3)})`);
console.log(`Narration subject detection (line level): precision ${np.toFixed(3)}, recall ${nr.toFixed(3)} (tp ${narrAll.tp}, fp ${narrAll.fp}, fn ${narrAll.fn})`);

const md = [
  `# Eval results`,
  ``,
  `Generated by \`npm run eval\` on ${new Date().toISOString().slice(0, 10)} with \`${process.env.GEMINI_MODEL ?? "gemini-3.5-flash"}\` over ${new Set(rows.map((r) => r.video)).size} fixture videos (${rows.length} child × video pairs). Ground truth: \`fixtures/videos/*/truth.json\` (see ASSETS.md for how it was labelled).`,
  ``,
  `| Metric | Value |`,
  `|---|---|`,
  `| Per-child presence error (mean absolute, percentage points) | **${mae.toFixed(2)}** |`,
  `| Presence interval IoU (mean) | **${meanIou.toFixed(3)}** |`,
  `| Visual-only interval IoU (mean) | ${meanIouV.toFixed(3)} |`,
  `| Narration subject detection precision (line level) | **${np.toFixed(3)}** |`,
  `| Narration subject detection recall (line level) | **${nr.toFixed(3)}** |`,
  ``,
  `| Video | Child | Truth % | Measured % | Error (pts) | IoU | Visual IoU |`,
  `|---|---|---|---|---|---|---|`,
  ...rows.map((r) => `| ${r.video} | ${r.child} | ${r.truthPct.toFixed(1)} | ${r.predPct.toFixed(1)} | ${r.errPts > 0 ? "+" : ""}${r.errPts.toFixed(1)} | ${r.iouPresence.toFixed(2)} | ${r.iouVisual.toFixed(2)} |`),
  ``,
].join("\n");
writeFileSync(join(ROOT, "docs", "EVAL.md"), md);
